#!/usr/bin/env bash

set -euo pipefail

TARGET="${1:-latest}"
TARGET="${TARGET#v}" # v2.0.0 and 2.0.0 name the same release
if [[ -n "${BASH_SOURCE[0]-}" ]]; then
  SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
else
  # When executed via `curl ... | bash`, BASH_SOURCE can be unset under `set -u`.
  SCRIPT_DIR="$(pwd -P)"
fi

# Stable X.Y.Z only: the version is spliced into the release tag, the asset
# URL, and the wheel filename below, and PEP 440 normalizes prerelease
# suffixes out of wheel filenames (1.2.3-rc1 → 1.2.3rc1) — prereleases are
# not installable through this script.
if [[ ! "${TARGET}" =~ ^(stable|latest|[0-9]+\.[0-9]+\.[0-9]+)$ ]]; then
  echo "Unknown version '${1}'. Give a release version such as 2.0.0, or nothing for the latest:" >&2
  echo "  curl -fsSL https://raw.githubusercontent.com/faisalmumtaz89/Cortex/main/install.sh | bash -s -- 2.0.0" >&2
  exit 1
fi

if [[ -t 1 ]]; then
  RED=$'\033[31m'
  GREEN=$'\033[32m'
  YELLOW=$'\033[33m'
  CYAN=$'\033[36m'
  BOLD=$'\033[1m'
  RESET=$'\033[0m'
else
  RED=""
  GREEN=""
  YELLOW=""
  CYAN=""
  BOLD=""
  RESET=""
fi

log() {
  echo "${CYAN}→${RESET} $*"
}

ok() {
  echo "${GREEN}✓${RESET} $*"
}

warn() {
  echo "${YELLOW}⚠${RESET} $*" >&2
}

die() {
  echo "${RED}✗${RESET} $*" >&2
  exit 1
}

pick_python() {
  local candidates=()
  if [[ -n "${CORTEX_PYTHON:-}" ]]; then
    candidates+=("${CORTEX_PYTHON}")
  fi
  candidates+=("python3.13" "python3.12" "python3.11" "python3")

  local candidate=""
  for candidate in "${candidates[@]}"; do
    if ! command -v "${candidate}" >/dev/null 2>&1; then
      continue
    fi
    # Debian/Ubuntu split venv/ensurepip into python3-venv: without them the
    # runtime venv cannot be created, so such a Python does not count.
    if "${candidate}" - <<'PY' >/dev/null 2>&1
import sys
if sys.version_info < (3, 11):
    raise SystemExit(1)
import ensurepip, venv  # noqa: F401
PY
    then
      echo "${candidate}"
      return 0
    fi
  done
  return 1
}

is_source_checkout() {
  if [[ ! -f "${SCRIPT_DIR}/pyproject.toml" ]] || [[ ! -d "${SCRIPT_DIR}/cortex" ]]; then
    return 1
  fi
  grep -q '^name = "cortex-llm"' "${SCRIPT_DIR}/pyproject.toml"
}

pick_downloader() {
  if command -v curl >/dev/null 2>&1; then
    echo "curl"
    return 0
  fi
  if command -v wget >/dev/null 2>&1; then
    echo "wget"
    return 0
  fi
  return 1
}

# ---- GitHub Releases: the SINGLE distribution channel -----------------------
#
# Cortex is installed from GitHub release assets: the versioned wheel
# (canonical PEP 427 filename — pip refuses anything else) plus a `.sha256`
# sibling generated by the release workflow. `stable`/`latest` resolve to a
# tag through GitHub's releases/latest redirect (no API, no rate limits); an
# explicit VERSION maps to tag vVERSION directly.
#
# CORTEX_RELEASE_BASE is a TEST seam (local stub servers). Anything that is
# not the real https github.com origin is refused unless
# CORTEX_ALLOW_INSECURE_BASE=1: the .sha256 shares the wheel's origin, so
# checksum verification is worthless against a hostile base.
RELEASE_BASE="${CORTEX_RELEASE_BASE:-https://github.com/faisalmumtaz89/Cortex}"
# One wheel per platform; detect_platform picks this machine's. Keep the table
# in step with cortex/ui_runtime/platforms.py (tests/test_packaging.py).
WHEEL_PLAT_TAG=""
UV_TRIPLE=""
# uv installs a private Python when the system has no usable Python 3.11+.
UV_VERSION="0.13.0"

require_trusted_release_base() {
  case "${RELEASE_BASE}" in
    https://github.com/*) ;;
    *)
      if [[ "${CORTEX_ALLOW_INSECURE_BASE:-0}" != "1" ]]; then
        die "CORTEX_RELEASE_BASE must be an https://github.com/... origin (got: ${RELEASE_BASE}). Set CORTEX_ALLOW_INSECURE_BASE=1 only for local stub testing."
      fi
      ;;
  esac
}

resolve_release_tag() {
  # Prints the release tag (vX.Y.Z) on stdout; dies on anything unusable.
  if [[ "${TARGET}" != "stable" ]] && [[ "${TARGET}" != "latest" ]]; then
    echo "v${TARGET}"
    return 0
  fi

  local probe_url="${RELEASE_BASE}/releases/latest"
  local answer="" http_code="" redirect_url="" tag=""
  # Redirects intentionally NOT followed: the Location header IS the answer.
  answer="$(curl -sS -o /dev/null -w '%{http_code} %{redirect_url}' "${probe_url}")" \
    || die "Could not reach ${probe_url} — check your network and try again."
  http_code="${answer%% *}"
  redirect_url="${answer#* }"

  if [[ "${http_code}" == "404" ]]; then
    die "Release lookup failed: ${probe_url} answered HTTP 404 (repository not found?)."
  fi
  if [[ ! "${http_code}" =~ ^30[0-9]$ ]]; then
    die "Release lookup failed: unexpected HTTP ${http_code} from ${probe_url} — try again later."
  fi
  if [[ "${redirect_url}" != */releases/tag/* ]]; then
    # A repo with ZERO releases redirects to the /releases index page (not a
    # 404) — there is nothing to install yet.
    die "Cortex has no published releases yet — nothing to install. To install from a source checkout instead: git clone https://github.com/faisalmumtaz89/Cortex.git && cd Cortex && ./install.sh"
  fi
  tag="${redirect_url##*/releases/tag/}"
  tag="${tag%%/*}"
  if [[ ! "${tag}" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    die "Latest release tag '${tag}' is not a stable vX.Y.Z version — refusing to build a download URL from it."
  fi
  echo "${tag}"
}

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | awk '{print $1}'
  elif command -v openssl >/dev/null 2>&1; then
    openssl dgst -sha256 "$1" | awk '{print $NF}'
  else
    die "No SHA-256 tool found (sha256sum, shasum or openssl) to verify the download."
  fi
}

version_at_least() {
  # $1 >= $2, for dotted numeric versions.
  [[ "$(printf '%s\n%s\n' "$2" "$1" | sort -t. -k1,1n -k2,2n -k3,3n | head -n1)" == "$2" ]]
}

detect_platform() {
  local os arch
  os="$(uname -s)"
  arch="$(uname -m)"
  case "${os}" in
    Darwin)
      local macos
      macos="$(sw_vers -productVersion 2>/dev/null || echo 0)"
      version_at_least "${macos}" "13.0" \
        || die "Cortex needs macOS 13 or later (this Mac runs ${macos})."
      # Under Rosetta uname reports x86_64 on Apple Silicon: use the native build.
      if [[ "${arch}" == "arm64" ]] || [[ "$(sysctl -n hw.optional.arm64 2>/dev/null || echo 0)" == "1" ]]; then
        WHEEL_PLAT_TAG="macosx_13_0_arm64"; UV_TRIPLE="aarch64-apple-darwin"
      elif [[ "${arch}" == "x86_64" ]]; then
        WHEEL_PLAT_TAG="macosx_13_0_x86_64"; UV_TRIPLE="x86_64-apple-darwin"
      else
        die "Unsupported Mac architecture: ${arch}."
      fi
      ;;
    Linux)
      if ldd --version 2>&1 | grep -qi musl; then
        die "This Linux uses musl libc (for example Alpine). Cortex needs a glibc-based distribution such as Debian, Ubuntu, Fedora or Arch."
      fi
      local glibc
      glibc="$(getconf GNU_LIBC_VERSION 2>/dev/null | awk '{print $2}')"
      if [[ -n "${glibc}" ]] && ! version_at_least "${glibc}" "2.28"; then
        die "Cortex needs glibc 2.28 or later (Debian 10, Ubuntu 20.04, RHEL 8 or newer); this system has ${glibc}."
      fi
      case "${arch}" in
        x86_64|amd64) WHEEL_PLAT_TAG="manylinux_2_28_x86_64"; UV_TRIPLE="x86_64-unknown-linux-gnu" ;;
        aarch64|arm64) WHEEL_PLAT_TAG="manylinux_2_28_aarch64"; UV_TRIPLE="aarch64-unknown-linux-gnu" ;;
        *) die "Unsupported Linux architecture: ${arch}. Cortex runs on x86_64 and arm64." ;;
      esac
      ;;
    MINGW*|MSYS*|CYGWIN*)
      die "On Windows, Cortex runs inside WSL. In PowerShell, run:  irm https://raw.githubusercontent.com/faisalmumtaz89/Cortex/main/install.ps1 | iex"
      ;;
    *)
      die "Unsupported system: ${os}. Cortex runs on macOS and Linux (and on Windows through WSL)."
      ;;
  esac
}

install_managed_python() {
  # Prints the path of a private Python 3.12 that uv installs under INSTALL_ROOT.
  local uv_dir="${INSTALL_ROOT}/uv"
  local uv_bin="${uv_dir}/uv"
  export UV_PYTHON_INSTALL_DIR="${INSTALL_ROOT}/python"
  if [[ ! -x "${uv_bin}" ]]; then
    local archive="uv-${UV_TRIPLE}.tar.gz"
    local url="https://github.com/astral-sh/uv/releases/download/${UV_VERSION}/${archive}"
    local tmp=""
    tmp="$(mktemp -d "${TMPDIR:-/tmp}/cortex-uv.XXXXXX")"
    log "Downloading uv ${UV_VERSION} to install a private Python" >&2
    curl -fsSL "${url}" -o "${tmp}/${archive}" || die "Download failed: ${url}"
    curl -fsSL "${url}.sha256" -o "${tmp}/${archive}.sha256" \
      || die "No checksum at ${url}.sha256 — refusing to run an unverified uv."
    local want="" got=""
    want="$(awk '{print $1}' "${tmp}/${archive}.sha256")"
    got="$(sha256_of "${tmp}/${archive}")"
    [[ "${want}" =~ ^[0-9a-f]{64}$ ]] && [[ "${want}" == "${got}" ]] \
      || die "Checksum mismatch for ${archive} — installing nothing."
    tar -xzf "${tmp}/${archive}" -C "${tmp}"
    mkdir -p "${uv_dir}"
    cp "${tmp}/uv-${UV_TRIPLE}/uv" "${uv_bin}"
    chmod +x "${uv_bin}"
    rm -rf "${tmp}"
  fi
  log "Installing a private Python 3.12 in ${UV_PYTHON_INSTALL_DIR}" >&2
  "${uv_bin}" python install 3.12 >&2 || die "Could not install Python 3.12 with uv."
  UV_PYTHON_PREFERENCE=only-managed "${uv_bin}" python find 3.12 \
    || die "uv installed Python 3.12 but could not find it."
}

add_to_path() {
  # Makes BIN_DIR reachable from new terminals; prints what it did.
  # Guarded, so a profile that also sources another one adds it only once.
  local line="case \":\$PATH:\" in *\":${BIN_DIR}:\"*) ;; *) export PATH=\"${BIN_DIR}:\$PATH\" ;; esac"
  local profiles=()
  case "$(basename "${SHELL:-sh}")" in
    zsh) profiles=("${ZDOTDIR:-$HOME}/.zshrc") ;;
    bash)
      # Interactive shells read ~/.bashrc; login shells (macOS Terminal, SSH,
      # tmux by default) read only the first of these that exists.
      profiles=("${HOME}/.bashrc")
      local login="" candidate
      for candidate in .bash_profile .bash_login .profile; do
        if [[ -f "${HOME}/${candidate}" ]]; then
          login="${HOME}/${candidate}"
          break
        fi
      done
      if [[ -z "${login}" ]]; then
        if [[ "$(uname -s)" == "Darwin" ]]; then login="${HOME}/.bash_profile"; else login="${HOME}/.profile"; fi
      fi
      profiles+=("${login}")
      ;;
    fish)
      mkdir -p "${HOME}/.config/fish/conf.d"
      echo "fish_add_path ${BIN_DIR}" > "${HOME}/.config/fish/conf.d/cortex.fish"
      ok "Added ${BIN_DIR} to PATH in ${HOME}/.config/fish/conf.d/cortex.fish"
      return 0
      ;;
    *) profiles=("${HOME}/.profile") ;;
  esac
  local profile
  for profile in "${profiles[@]}"; do
    if ! grep -qsF "${BIN_DIR}" "${profile}"; then
      printf '\n# Added by the Cortex installer\n%s\n' "${line}" >> "${profile}"
      ok "Added ${BIN_DIR} to PATH in ${profile}"
    fi
  done
}

download_and_verify_wheel() {
  # $1 = release tag (vX.Y.Z), $2 = destination directory.
  # Downloads the wheel under its CANONICAL filename (pip rejects renamed
  # wheels), verifies it against the .sha256 sibling asset, and prints the
  # verified wheel path on stdout. Any failure installs nothing.
  local tag="$1"
  local work_dir="$2"
  local version="${tag#v}"
  local wheel_name="cortex_llm-${version}-py3-none-${WHEEL_PLAT_TAG}.whl"
  local wheel_url="${RELEASE_BASE}/releases/download/${tag}/${wheel_name}"
  local wheel_path="${work_dir}/${wheel_name}"

  log "Downloading ${wheel_name}" >&2
  # -L is required: GitHub asset URLs redirect to a signed CDN URL.
  curl -fsSL "${wheel_url}" -o "${wheel_path}" \
    || die "Download failed: ${wheel_url} — does release ${tag} exist with a wheel asset?"
  curl -fsSL "${wheel_url}.sha256" -o "${wheel_path}.sha256" \
    || die "No checksum asset at ${wheel_url}.sha256 — refusing to install an unverified wheel."

  local want="" got=""
  want="$(awk '{print $1}' "${wheel_path}.sha256")"
  if [[ ! "${want}" =~ ^[0-9a-f]{64}$ ]]; then
    die "Malformed .sha256 asset for ${wheel_name} — refusing to install."
  fi
  got="$(sha256_of "${wheel_path}")"
  if [[ "${want}" != "${got}" ]]; then
    die "Checksum mismatch for ${wheel_name} (want ${want}, got ${got}) — installing nothing."
  fi
  ok "Checksum verified: ${got}" >&2
  echo "${wheel_path}"
}

purge_stale_site_package_cortex() {
  local python_bin="$1"
  local source_root="$2"

  "${python_bin}" - "$source_root" <<'PY'
import shutil
import site
import sys
from pathlib import Path

source_root = Path(sys.argv[1]).resolve()
removed = []

site_dirs = []
try:
    site_dirs.extend(Path(p).resolve() for p in site.getsitepackages())
except Exception:
    pass
user_site = site.getusersitepackages()
if isinstance(user_site, str) and user_site:
    site_dirs.append(Path(user_site).resolve())

for base in site_dirs:
    candidate = base / "cortex"
    if not candidate.exists() or not candidate.is_dir():
        continue
    # Keep source tree packages untouched; only purge stale copies in site-packages.
    if source_root in candidate.parents:
        continue
    shutil.rmtree(candidate)
    removed.append(str(candidate))

for path in removed:
    print(path)
PY
}

clear_hidden_site_flags() {
  local python_bin="$1"
  command -v chflags >/dev/null 2>&1 || return 0

  local site_dirs=""
  site_dirs="$("${python_bin}" - <<'PY'
import site
from pathlib import Path

dirs = []
try:
    dirs.extend(site.getsitepackages())
except Exception:
    pass
user_site = site.getusersitepackages()
if isinstance(user_site, str) and user_site:
    dirs.append(user_site)

for value in dirs:
    path = Path(value).expanduser().resolve()
    print(path)
PY
)"

  while IFS= read -r dir; do
    [[ -z "${dir}" ]] && continue
    [[ -d "${dir}" ]] || continue
    chflags nohidden "${dir}" >/dev/null 2>&1 || true
    find "${dir}" -maxdepth 1 -type f -name "*.pth" -exec chflags nohidden {} + >/dev/null 2>&1 || true
  done <<< "${site_dirs}"
}

ensure_source_package_link() {
  local python_bin="$1"
  local source_root="$2"

  "${python_bin}" - "$source_root" <<'PY'
import shutil
import site
import sys
from pathlib import Path

source_root = Path(sys.argv[1]).resolve()
source_package = source_root / "cortex"
if not source_package.is_dir():
    raise SystemExit("missing source package directory")

site_dirs = []
try:
    site_dirs.extend(Path(p).resolve() for p in site.getsitepackages())
except Exception:
    pass
user_site = site.getusersitepackages()
if isinstance(user_site, str) and user_site:
    site_dirs.append(Path(user_site).resolve())

created_link = None
for base in site_dirs:
    if not base.exists():
        continue
    candidate = base / "cortex"
    if candidate.exists() or candidate.is_symlink():
        if candidate.is_symlink() and candidate.resolve() == source_package:
            created_link = candidate
            break
        if candidate.is_dir() and not candidate.is_symlink():
            shutil.rmtree(candidate)
        else:
            candidate.unlink()
    candidate.symlink_to(source_package, target_is_directory=True)
    created_link = candidate
    break

if created_link is None:
    raise SystemExit("unable to create site-packages source link for cortex")

print(created_link)
PY
}

ensure_bun() {
  if command -v bun >/dev/null 2>&1; then
    command -v bun
    return 0
  fi

  local bun_local="${HOME}/.bun/bin/bun"
  if [[ -x "${bun_local}" ]]; then
    echo "${bun_local}"
    return 0
  fi

  local downloader
  downloader="$(pick_downloader || true)"
  if [[ -z "${downloader}" ]]; then
    die "Bun is required to build the OpenTUI sidecar, but neither curl nor wget is available."
  fi

  log "Bun not found. Installing Bun..." >&2
  if [[ "${downloader}" == "curl" ]]; then
    curl -fsSL https://bun.sh/install | bash -s -- >/dev/null
  else
    wget -q -O - https://bun.sh/install | bash -s -- >/dev/null
  fi

  if command -v bun >/dev/null 2>&1; then
    command -v bun
    return 0
  fi
  if [[ -x "${bun_local}" ]]; then
    echo "${bun_local}"
    return 0
  fi

  die "Bun installation failed. Install manually from https://bun.sh and rerun installer."
}

ensure_source_sidecar() {
  local source_root="$1"
  local sidecar="${source_root}/cortex/ui_runtime/bin/cortex-tui"
  local frontend_dir="${source_root}/frontend/cortex-tui"
  if [[ ! -d "${frontend_dir}" ]]; then
    die "OpenTUI frontend sources not found at ${frontend_dir}."
  fi

  local needs_build="0"
  local reason="missing"
  if [[ ! -x "${sidecar}" ]]; then
    needs_build="1"
    reason="missing"
  else
    # Rebuild when frontend sources/config are newer than the bundled sidecar.
    local stale_marker=""
    stale_marker="$(find "${frontend_dir}" -type f \
      \( -name "*.ts" -o -name "*.tsx" -o -name "package.json" -o -name "bun.lock*" -o -name "tsconfig*.json" \) \
      -newer "${sidecar}" -print -quit 2>/dev/null || true)"
    if [[ -n "${stale_marker}" ]]; then
      needs_build="1"
      reason="stale"
    fi
  fi

  if [[ "${needs_build}" != "1" ]]; then
    return 0
  fi

  local bun_bin
  bun_bin="$(ensure_bun)"

  if [[ "${reason}" == "stale" ]]; then
    log "Rebuilding OpenTUI sidecar (frontend sources changed)..."
  else
    log "Building OpenTUI sidecar..."
  fi
  (
    cd "${frontend_dir}"
    "${bun_bin}" install >/dev/null
    "${bun_bin}" run build >/dev/null
  )

  if [[ ! -x "${sidecar}" ]]; then
    die "OpenTUI sidecar build failed: ${sidecar} was not produced."
  fi

  ok "OpenTUI sidecar built."
}

verify_sidecar_runtime() {
  local sidecar_path
  local sidecar_ok
  sidecar_path="$("${RUNTIME_PYTHON}" - <<'PY'
from cortex.ui_runtime.launcher import _bundled_binary
print(_bundled_binary())
PY
)"
  sidecar_ok="$("${RUNTIME_PYTHON}" - <<'PY'
import os
from cortex.ui_runtime.launcher import _bundled_binary
path = _bundled_binary()
print("1" if path.exists() and os.access(path, os.X_OK) else "0")
PY
)"

  if [[ "${sidecar_ok}" != "1" ]]; then
    die "OpenTUI sidecar is missing or not executable at ${sidecar_path}. Installation incomplete."
  fi
  ok "OpenTUI sidecar ready: ${sidecar_path}"
}

detect_platform
command -v curl >/dev/null 2>&1 || die "curl is required to install Cortex (for example: sudo apt install curl)."
INSTALL_ROOT="${CORTEX_INSTALL_ROOT:-$HOME/.cortex/install}"
VENV_DIR="${INSTALL_ROOT}/venv"
BIN_DIR="${CORTEX_BIN_DIR:-$HOME/.local/bin}"
LOCAL_LINK="${BIN_DIR}/cortex"

mkdir -p "${INSTALL_ROOT}" "${BIN_DIR}"

# A system Python 3.11+ with venv support, or else a private one (no admin
# rights, no package manager). CORTEX_MANAGED_PYTHON=1 always uses the private one.
PYTHON_BIN=""
if [[ "${CORTEX_MANAGED_PYTHON:-0}" != "1" ]]; then
  PYTHON_BIN="$(pick_python || true)"
fi
if [[ -z "${PYTHON_BIN}" ]]; then
  PYTHON_BIN="$(install_managed_python)"
fi
log "Using Python $("${PYTHON_BIN}" -c 'import platform, sys; print(platform.python_version(), "at", sys.executable)')"

if [[ ! -x "${VENV_DIR}/bin/python" ]]; then
  log "Creating isolated runtime at ${VENV_DIR}"
  "${PYTHON_BIN}" -m venv "${VENV_DIR}"
fi

PIP="${VENV_DIR}/bin/pip"
# Downloads go straight into the runtime: no pip cache left in ~/.cache, and
# no package-index call for pip's own version.
export PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1
RUNTIME_PYTHON="${VENV_DIR}/bin/python"

log "Upgrading installer tooling"
"${PIP}" install --quiet --disable-pip-version-check --upgrade pip setuptools wheel >/dev/null
clear_hidden_site_flags "${RUNTIME_PYTHON}"

INSTALL_MODE="release"
if [[ "${TARGET}" =~ ^(stable|latest)$ ]] && is_source_checkout && [[ "${CORTEX_INSTALL_SOURCE:-1}" == "1" ]]; then
  INSTALL_MODE="source"
fi

if [[ "${INSTALL_MODE}" == "source" ]]; then
  log "Installing Cortex from source checkout: ${SCRIPT_DIR}"
  stale_removed="$(purge_stale_site_package_cortex "${RUNTIME_PYTHON}" "${SCRIPT_DIR}" || true)"
  if [[ -n "${stale_removed}" ]]; then
    warn "Removed stale site-packages Cortex module(s):"
    while IFS= read -r line; do
      [[ -n "${line}" ]] && echo "  - ${line}" >&2
    done <<< "${stale_removed}"
  fi
  "${PIP}" install --upgrade -e "${SCRIPT_DIR}"
  clear_hidden_site_flags "${RUNTIME_PYTHON}"
  SOURCE_LINK_PATH="$(ensure_source_package_link "${RUNTIME_PYTHON}" "${SCRIPT_DIR}")" \
    || die "Unable to create stable source link in site-packages."
  ok "Source package link: ${SOURCE_LINK_PATH}"

  SOURCE_IMPORT_PATH="$("${RUNTIME_PYTHON}" - "$SCRIPT_DIR" <<'PY'
import sys
from pathlib import Path
source_root = Path(sys.argv[1]).resolve()
import cortex
module_path = Path(cortex.__file__).resolve()
print(module_path)
if source_root not in module_path.parents:
    raise SystemExit(1)
PY
)" || die "Editable install did not resolve cortex imports to source checkout. Re-run installer."

  ok "Python import path: ${SOURCE_IMPORT_PATH}"
  ensure_source_sidecar "${SCRIPT_DIR}"
else
  command -v curl >/dev/null 2>&1 \
    || die "curl is required to download Cortex release assets."
  require_trusted_release_base

  RELEASE_TAG="$(resolve_release_tag)"
  log "Installing Cortex ${RELEASE_TAG#v} from GitHub release ${RELEASE_TAG}"

  WORK_DIR="$(mktemp -d "${TMPDIR:-/tmp}/cortex-wheel.XXXXXX")"
  trap 'rm -rf "${WORK_DIR}"' EXIT

  WHEEL_PATH="$(download_and_verify_wheel "${RELEASE_TAG}" "${WORK_DIR}")"
  # Local-wheel installs upgrade AND downgrade without extra flags; only the
  # cortex-llm artifact itself comes from the release — new/changed
  # dependencies still resolve from the package index.
  log "Installing Cortex and its dependencies (a first install takes a minute or two)"
  "${PIP}" install --quiet --disable-pip-version-check "${WHEEL_PATH}" \
    || die "pip could not install ${WHEEL_PATH##*/}; see the messages above."
  clear_hidden_site_flags "${RUNTIME_PYTHON}"
fi

if [[ ! -x "${VENV_DIR}/bin/cortex" ]]; then
  die "Installation completed but cortex entrypoint was not created."
fi

verify_sidecar_runtime

ln -sfn "${VENV_DIR}/bin/cortex" "${LOCAL_LINK}"
chmod +x "${VENV_DIR}/bin/cortex"

INSTALLED_VERSION="$("${RUNTIME_PYTHON}" - <<'PY'
from importlib.metadata import version
print(version("cortex-llm"))
PY
)"

ok "Installed Cortex ${INSTALLED_VERSION}"
ok "Launcher: ${LOCAL_LINK}"

NEW_SHELL_NEEDED="0"
if [[ ":$PATH:" != *":${BIN_DIR}:"* ]]; then
  # CORTEX_NO_MODIFY_PATH=1 leaves shell profiles alone.
  if [[ "${CORTEX_NO_MODIFY_PATH:-0}" == "1" ]]; then
    warn "${BIN_DIR} is not on PATH. Add it with: export PATH=\"${BIN_DIR}:\$PATH\""
  else
    add_to_path
    NEW_SHELL_NEEDED="1"
  fi
fi

echo
echo "${BOLD}Installation complete.${RESET}"
if [[ "${NEW_SHELL_NEEDED}" == "1" ]]; then
  echo "Open a new terminal (or run: export PATH=\"${BIN_DIR}:\$PATH\"), then run: cortex"
else
  echo "Run: cortex"
fi
echo "Then add a key with /login (or set OPENAI_API_KEY, ANTHROPIC_API_KEY, ...) and pick a model with /model."
echo
